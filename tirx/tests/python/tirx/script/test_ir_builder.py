def test_symbolic_tensor_indices():
    m, n, k = [tirx.Var(name, "int32") for name in ("m", "n", "k")]
    tensor = tirx.Var("tensor", tirx.TensorType((m, n), "float32"))
    actual = T.tensor_indices(tensor, k)
    for index, expected in zip(actual, [k // n, k % n]):
        tvm_tirx.ir.assert_structural_equal(index, expected)


@pytest.mark.parametrize("layout", [None, TileLayout(S[(2, 3) : (1, 2)])])
def test_flat_tensor_store_preserves_identity_and_emits_once(layout):
    tensor = tirx.Var(
        "tensor",
        tirx.TensorType(
            (2, 3),
            "float32",
            layout=TileLayout.from_iters(layout.shard, offset={"m": 2})
            if layout is not None
            else TileLayout(S[(2, 3) : (5, 1)] + 2),
        ),
    )
    indices = T.tensor_indices(tensor, 4)
    load = tensor[indices]
    assert load.source.same_as(tensor)
    with IRBuilder() as ib:
        receipt = T.tensor_store(tensor, indices, load + 1)
        T.emit_(receipt)
    store = ib.get()
    assert isinstance(store, tvm_tirx.ir.TensorStore)
    assert store.dest.same_as(tensor)
    assert list(store.indices) == [1, 1]
    assert store.value.a.source.same_as(tensor)


def test_python_bool_control_conditions():
    with IRBuilder() as ib:
        with T.function():
            with T.if_(True):
                with T.then_():
                    T.evaluate(T.call_extern("true_branch", ty="int32"))
            with T.while_(False):
                T.evaluate(T.call_extern("false_loop", ty="int32"))
            T.assert_(True, "ok")
    statements = list(ib.get().body.seq)
    assert isinstance(statements[0], tvm_tirx.ir.If)
    assert isinstance(statements[1], tvm_tirx.ir.While)
    assert isinstance(statements[2], tvm_tirx.ir.AssertStmt)
    assert [bool(stmt.condition.value) for stmt in statements] == [True, False, True]
    assert all(str(stmt.condition.ty) == "bool" for stmt in statements)


@pytest.mark.parametrize("declare", [False, True])
def test_concrete_mutable_scalar(declare):
    with IRBuilder() as ib:
        with T.function():
            if declare:
                allocation = T.alloc_tensor(ty_args=[T.Tensor((4,), "int32", scope="local")])
                owner = tirx.Var("owner", allocation.ty)
                T.emit_(T.Bind(owner, allocation))
                scalar = T.decl_scalar(
                    "int32", owner.data, "local", layout=T.TileLayout(T.S[(1,)] + (2))
                )
            else:
                scalar = T.alloc_scalar("int32", "local")
            assert type(scalar) is tvm_tirx.ir.TensorLoad
            named = T.decl_mutable_cell_(scalar, name="counter")
            assert named.same_as(scalar)
            assert scalar.source.name == "counter"
            T.emit_(T.set_mutable_cell_(scalar, 3))
            T.emit_(T.set_mutable_cell_(scalar, scalar + 1))
    stores = []
    tvm_ffi.structural_walk(
        ib.get().body,
        lambda node: stores.append(node) if isinstance(node, tvm_tirx.ir.TensorStore) else None,
    )
    assert len(stores) == 2
    assert all(store.dest.same_as(scalar.source) for store in stores)
    if declare:
        declaration = next(
            stmt for stmt in ib.get().body.seq if _is_tensor_binding(stmt, "tirx.decl_tensor")
        )
        assert declaration.var.same_as(scalar.source)
        tvm_tirx.ir.assert_structural_equal(declaration.value.args[0], owner.data)
        assert scalar.source.ty.layout.apply(0)["m"] == 2


def test_local_scalar_initialization_and_assign():
    from tvm_tirx.script import tirx as TS
    from tvm_tirx.script.ir_builder.base import AlreadyEmitted

    assert TS.assign is T.assign
    loc = tvm_tirx.ir.SourceLoc(tvm_tirx.ir.SourceName("scalar.py"), 3, 1, 3, 20)
    annotations = {"alignment": 16}
    with IRBuilder() as ib:
        with T.function():
            with ib.with_loc(loc):
                scalar = T.local_scalar("int32", 2, name="counter", annotations=annotations)
                uninitialized = T.local_scalar()
                receipt = T.assign(scalar, 3)
                assert isinstance(receipt, AlreadyEmitted)
                T.emit_(receipt)
                source_receipt = T.assign(scalar.source, 4)
                allocation = T.alloc_tensor(ty_args=[T.Tensor((2,), "int32")])
                global_tensor = tirx.Var("global_tensor", allocation.ty)
                T.emit_(T.Bind(global_tensor, allocation))
                indexed_receipt = T.assign(global_tensor[1], 5)
                for invalid in (tirx.Var("immutable", "int32"), scalar + 1, global_tensor):
                    with pytest.raises(TypeError, match="scalar storage"):
                        T.assign(invalid, 6)
    statements = list(ib.get().body.seq)
    stores = [stmt for stmt in statements if isinstance(stmt, tvm_tirx.ir.TensorStore)]
    allocations = [stmt for stmt in statements if _is_tensor_binding(stmt, "tirx.alloc_tensor")]
    assert len(allocations) == 3
    assert len(stores) == 4
    assert statements[0].same_as(allocations[0])
    assert statements[1].same_as(stores[0])
    assert allocations[0].var.same_as(scalar.source)
    assert allocations[0].value.attrs["alignment"] == annotations["alignment"]
    assert scalar.source.name == "counter"
    assert scalar.source.ty.dtype == "int32"
    assert scalar.source.ty.scope == tvm_tirx.runtime.MemoryScope("local")
    assert scalar.source.ty.layout is None
    assert list(scalar.source.ty.shape) == [1]
    assert uninitialized.source.ty.dtype == "float32"
    assert all(store.dest.same_as(scalar.source) for store in stores[:3])
    assert stores[1].same_as(receipt.value)
    assert stores[2].same_as(source_receipt.value)
    assert stores[3].same_as(indexed_receipt.value)
    assert stores[3].dest.same_as(global_tensor)
    assert list(stores[3].indices) == [1]
    assert [store.value.value for store in stores] == [2, 3, 4, 5]
    assert all(store.loc.same_as(loc) for store in stores)

    @TS.function
    def parsed():
        scalar = TS.local_scalar("int32", 1)
        TS.assign(scalar, 2)
        scalar = 3

    parsed_stores = [stmt for stmt in parsed.body.seq if isinstance(stmt, tvm_tirx.ir.TensorStore)]
    assert len(parsed.body.seq) == 4
    assert [store.value.value for store in parsed_stores] == [1, 2, 3]
    assert all(store.dest.same_as(parsed.body.seq[0].var) for store in parsed_stores)
    assert all(isinstance(store.loc, tvm_tirx.ir.SourceLoc) for store in parsed_stores)
    assert [store.loc.start_line for store in parsed_stores] == list(
        range(parsed_stores[0].loc.start_line, parsed_stores[0].loc.start_line + 3)
    )


