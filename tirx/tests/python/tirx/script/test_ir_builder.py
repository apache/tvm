def _is_tensor_binding(node, *op_names):
    return (
        isinstance(node, tvm_tirx.ir.Bind)
        and isinstance(node.value, tvm_tirx.ir.Call)
        and isinstance(node.value.op, tvm_tirx.ir.Op)
        and node.value.op.name in op_names
    )


def test_ir_builder_tir_for():
    with IRBuilder() as ib:
        with T.serial(128) as a:
            with T.parallel(64) as b:
                with T.vectorized(32) as c:
                    with T.unroll(16) as d:
                        with T.parallel(8, annotations={"thread_binding": "threadIdx.x"}) as e:
                            T.evaluate(0)

    # the for generated by IRBuilder
    for_actual = ib.get()

    # the expected for
    thread_binding_expected = tvm_tirx.ir.For(
        loop_var=tirx.Var("", "int32"),
        min=0,
        extent=8,
        kind=tvm_tirx.ir.ForKind.PARALLEL,
        body=tvm_tirx.ir.Evaluate(0),
        annotations={"thread_binding": "threadIdx.x"},
    )
    unroll_expected = tvm_tirx.ir.For(
        loop_var=tirx.Var("", "int32"),
        min=0,
        extent=16,
        kind=tvm_tirx.ir.ForKind.UNROLLED,
        body=thread_binding_expected,
    )
    vectorized_expected = tvm_tirx.ir.For(
        loop_var=tirx.Var("", "int32"),
        min=0,
        extent=32,
        kind=tvm_tirx.ir.ForKind.VECTORIZED,
        body=unroll_expected,
    )
    parallel_expected = tvm_tirx.ir.For(
        loop_var=tirx.Var("", "int32"),
        min=0,
        extent=64,
        kind=tvm_tirx.ir.ForKind.PARALLEL,
        body=vectorized_expected,
    )
    for_expected = tvm_tirx.ir.For(
        loop_var=tirx.Var("", "int32"),
        min=0,
        extent=128,
        kind=tvm_tirx.ir.ForKind.DEFAULT,
        body=parallel_expected,
    )

    # Check if the generated ir is expected
    assert_structural_equal(for_actual, for_expected, map_free_vars=True)


