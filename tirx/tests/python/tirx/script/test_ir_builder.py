def test_ir_builder_tir_assert():
    with IRBuilder() as ib:
        with T.function():
            T.assert_(T.int32() == 0, message="a is 0")
            T.evaluate(T.call_extern("after_assert", ty="int32"))
    # the assert generated by IRBuilder
    assert_actual = ib.get().body

    # AssertStmt is a leaf. The frame emits the assert and then the body stmts as siblings.
    assert_expected = tvm_tirx.ir.SeqStmt(
        [
            tvm_tirx.ir.AssertStmt(
                T.int32() == 0,
                tvm_tirx.ir.StringImm("RuntimeError"),
                [tvm_tirx.ir.StringImm("a is 0")],
            ),
            tvm_tirx.ir.Evaluate(tirx.call_extern("after_assert", ty="int32")),
        ]
    )

    # Check if the generated ir is expected
    assert_structural_equal(assert_actual, assert_expected, map_free_vars=True)


def test_ir_builder_tir_bind():
    # Construct and emit a flat Bind statement with an explicit variable.
    assert T.Bind is tvm_tirx.ir.Bind
    with IRBuilder() as ib:
        v = tirx.Var("v", "int32")
        T.emit_(T.Bind(v, tvm_tirx.ir.IntImm("int32", 2)))
    # the binding generated by IRBuilder
    let_actual = ib.get()

    # Bind is now flat (no body), so a single Bind stmt is emitted.
    let_expected = tvm_tirx.ir.Bind(T.int32(), tvm_tirx.ir.IntImm("int32", 2))

    # Check if the generated ir is expected
    assert_structural_equal(let_actual, let_expected, map_free_vars=True)
    assert let_actual.var.same_as(v)


