def _is_tensor_binding(node, *op_names):
    return (
        isinstance(node, tvm_tirx.ir.Bind)
        and isinstance(node.value, tvm_tirx.ir.Call)
        and isinstance(node.value.op, tvm_tirx.ir.Op)
        and node.value.op.name in op_names
    )


def test_ir_builder_tir_function_base():
    with IRBuilder() as ib:
        with build_function():
            T.evaluate(0)

    # the function generated by IRBuilder
    function_actual = ib.get()

    # the expected function
    function_expected = tirx.Function(
        params=[],
        body=tvm_tirx.ir.Evaluate(0),
        ret_type=None,
        attrs=tvm_tirx.ir.make_node("ir.DictAttrs", **{"s_tir": True, "script.namespace": "s_tir"}),
    )

    # Check if the generated ir is expected
    assert_structural_equal(function_actual, function_expected, map_free_vars=True)


def test_ir_builder_loc_applies_to_emitted_stmt():
    loc = SourceLoc(SourceName("builder_test.py"), 7, 5, 7, 18)
    with IRBuilder() as ib:
        with build_function():
            with ib.with_loc(loc):
                T.evaluate(1)

    actual = ib.get().body[0].loc
    assert actual.source_name.name == "builder_test.py"
    assert (actual.start_line, actual.start_column, actual.end_line, actual.end_column) == (
        7,
        5,
        7,
        18,
    )


def test_ir_builder_tir_function_complete():
    with IRBuilder() as ib:
        with build_function():
            T.arg_("a", T.handle())
            T.arg_("b", T.int64())
            T.arg_("c", T.Tensor((128, 128), "float32"))
            tensor_d = T.arg_("d", T.Tensor((64, 64), "int64"))
            e = T.arg_("e", T.Tensor((1024,), "int8"))
            T.func_attr({"key": "value"})
            T.func_ret(tvm_tirx.ir.PrimType("int64"))

            T.evaluate(0)

    # the function generated by IRBuilder
    function_actual = ib.get()

    # the expected function
    c_tensor = tirx.decl_tensor((128, 128), "float32", name="c", layout=None)
    d_tensor = tirx.decl_tensor((64, 64), "int64", name="d", layout=None)
    e_tensor = tirx.decl_tensor((1024,), "int8", name="e", layout=None)
    function_expected = tirx.Function(
        params=[
            tirx.Var("a", tvm_tirx.ir.PtrType(tvm_tirx.ir.PrimType("void"))),
            tirx.Var("b", "int64"),
            c_tensor,
            d_tensor,
            e_tensor,
        ],
        body=tvm_tirx.ir.Evaluate(0),
        ret_type=tvm_tirx.ir.PrimType("int64"),
        attrs=tvm_tirx.ir.make_node(
            "ir.DictAttrs", **{"key": "value", "s_tir": True, "script.namespace": "s_tir"}
        ),
    )

    # Check if the generated ir is expected
    assert_structural_equal(function_actual, function_expected, map_free_vars=True)


