def format_output(path, content):
    """Use the same pinned formatters as pre-commit, without importing TVM."""
    if path.suffix == ".py":
        for command in (
            ["ruff", "format", "--stdin-filename", str(path), "-"],
            ["ruff", "check", "--fix", "--stdin-filename", str(path), "-"],
            ["ruff", "format", "--stdin-filename", str(path), "-"],
        ):
            content = subprocess.run(
                command, input=content, text=True, capture_output=True, check=True, cwd=ROOT
            ).stdout
    elif path.suffix == ".h":
        content = subprocess.run(
            ["clang-format", "--assume-filename=" + str(path)],
            input=content,
            text=True,
            capture_output=True,
            check=True,
            cwd=ROOT,
        ).stdout
    return content


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        DIRECTORY / "_generated.py": python_api(),
        ROOT / "src/backend/cuda/launch/launch_fields.h": native_fields(),
        ROOT / "src/backend/cuda/launch/launch_attributes.h": native_attributes(),
        ROOT / "docs/tirx/api/cuda_launch.rst": documentation(),
    }
    for path in list(outputs):
        outputs[path] = format_output(path, outputs[path])
    support = "\n".join(
        [
            outputs[ROOT / "src/backend/cuda/launch/launch_fields.h"],
            outputs[ROOT / "src/backend/cuda/launch/launch_attributes.h"].replace(
                '#include "launch_fields.h"', ""
            ),
            (ROOT / "src/backend/cuda/launch/launch_config.h")
            .read_text()
            .replace('#include "launch_attributes.h"', ""),
        ]
    )
    outputs[ROOT / "src/backend/cuda/launch/launch_source.h"] = (
        CPP_LICENSE
        + "\n// Generated by launch/generate.py; edit the registry or launch_config.h.\n"
        "#ifndef TVM_BACKEND_CUDA_LAUNCH_LAUNCH_SOURCE_H_\n"
        "#define TVM_BACKEND_CUDA_LAUNCH_LAUNCH_SOURCE_H_\n"
        'namespace tvm_cuda_launch {\ninline constexpr const char* kSupportSource = R"TVM_CUDA_LAUNCH(\n'
        + support
        + '\n)TVM_CUDA_LAUNCH";\n}\n#endif\n'
    )
    source_path = ROOT / "src/backend/cuda/launch/launch_source.h"
    outputs[source_path] = format_output(source_path, outputs[source_path])
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("Stale CUDA launch generated files: " + ", ".join(stale))


if __name__ == "__main__":
    main()
